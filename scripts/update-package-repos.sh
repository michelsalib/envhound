#!/bin/sh
# Opens a pull request in the Homebrew tap and in the Scoop bucket with the files scripts/packages.ts
# wrote for a release, and turns on auto-merge: each lands once that repository's install CI passes.
# Run by the release workflow's publish job; by hand, after a release:
#   bun scripts/packages.ts 0.4.2 SHA256SUMS dist/packages
#   GH_TOKEN=... sh scripts/update-package-repos.sh 0.4.2 dist/packages
# GH_TOKEN needs Contents and Pull requests (read and write) on both repositories. Everything goes
# through GitHub's API: no clone, and the token is never written to disk or into a git remote.
set -eu

version=$1
dir=$2
owner=michelsalib
branch=envhound-$version

case $version in
  *[!0-9.]* | "") echo "update-package-repos: version must look like 0.4.2, not $version" >&2; exit 2 ;;
esac

# $1: repository, $2: file under $dir, $3: its path in the repository
update() {
  repo=$owner/$1
  file=$dir/$2
  path=$3
  [ -f "$file" ] || { echo "update-package-repos: $file is missing" >&2; exit 1; }
  base=$(gh api "repos/$repo/git/ref/heads/main" --jq .object.sha)
  gh api "repos/$repo/git/refs" -f ref="refs/heads/$branch" -f sha="$base" >/dev/null
  # the file's current blob on that branch, which the contents API needs to replace it
  old=$(gh api "repos/$repo/contents/$path?ref=$branch" --jq .sha)
  gh api -X PUT "repos/$repo/contents/$path" \
    -f message="envhound $version" \
    -f branch="$branch" \
    -f sha="$old" \
    -f content="$(base64 <"$file" | tr -d '\n')" >/dev/null
  url=$(gh pr create -R "$repo" --head "$branch" --base main \
    --title "envhound $version" \
    --body "Generated by envhound's release workflow from the v$version release's SHA256SUMS (https://github.com/$owner/envhound/releases/tag/v$version). Merges itself once the install checks pass.")
  gh pr merge -R "$repo" --auto --merge "$url"
  echo "$repo: $url"
}

update homebrew-envhound Formula/envhound.rb Formula/envhound.rb
update scoop-envhound envhound.json bucket/envhound.json
